"""
modules/report.py

Audit Report Generator
-------------------------
Formats the outputs of analyzer.py, estimator.py, and generator.py into
a clean, shareable Markdown report with defensive policy recommendations.
Purely a text-formatting module -- no external calls.
"""

from datetime import datetime
from typing import List, Optional


def _complexity_line(label: str, passed: bool) -> str:
    mark = "✅" if passed else "❌"
    return f"- {mark} {label}"


def generate_policy_recommendations(analysis: dict) -> List[str]:
    """Produce a short list of defensive recommendations based on findings."""
    recs = []
    complexity = analysis.get("complexity", {})

    if analysis.get("is_common_weak"):
        recs.append(
            "This password (or one very close to it) appears on common "
            "breached-password lists. It should be rejected outright by "
            "any password policy, regardless of its character complexity."
        )
    if not complexity.get("length_ok_12"):
        recs.append(
            "Enforce a minimum length of 12+ characters. Length is the "
            "single strongest contributor to entropy and resistance to "
            "offline brute-force attacks."
        )
    if not complexity.get("has_uppercase") or not complexity.get("has_lowercase"):
        recs.append(
            "Require a mix of uppercase and lowercase letters to widen "
            "the effective character set."
        )
    if not complexity.get("has_digit"):
        recs.append("Require at least one numeric character.")
    if not complexity.get("has_symbol"):
        recs.append(
            "Require at least one special/symbol character to further "
            "widen the keyspace."
        )
    if not complexity.get("no_repeated_chars"):
        recs.append(
            "Avoid repeated character runs (e.g. 'aaa', '111') -- these "
            "reduce effective entropy and are heavily targeted by "
            "pattern-based cracking rules."
        )

    recs.append(
        "Encourage passphrases (multiple random words) over single "
        "complex words -- they are typically easier to remember and "
        "harder to brute-force."
    )
    recs.append(
        "Deploy multi-factor authentication (MFA) everywhere possible; "
        "no password policy alone fully mitigates credential compromise."
    )
    recs.append(
        "Use a slow, salted hashing algorithm (bcrypt, scrypt, or "
        "Argon2) for stored credentials -- this dramatically increases "
        "real-world crack time versus the fast-hash assumption used in "
        "this report's illustrative estimate."
    )
    recs.append(
        "Periodically audit existing credential hashes OFFLINE against "
        "organization-specific wordlists (e.g. generated from company "
        "names, product names) to catch predictable employee password "
        "reuse before attackers do."
    )
    return recs


def generate_markdown_report(
    password_label: str,
    analysis: dict,
    crack_time: dict,
    wordlist: Optional[List[str]] = None,
    wordlist_base_keyword: Optional[str] = None,
) -> str:
    """
    Compile analysis + crack-time + (optional) generated wordlist into a
    single Markdown report string, ready for download/display.

    `password_label` should NOT be the raw password itself in shared
    reports -- callers may pass a masked label (e.g. "Tested Password #1")
    to avoid embedding real secrets in exported files. The Streamlit app
    lets the user choose whether to include the raw password.
    """
    now = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
    complexity = analysis.get("complexity", {})

    lines = []
    lines.append("# Password Security Audit Report")
    lines.append("")
    lines.append(f"**Generated:** {now}  ")
    lines.append(f"**Subject:** {password_label}")
    lines.append("")
    lines.append(
        "> This report is generated by an offline, educational password "
        "auditing toolkit. All figures are mathematical estimates. No "
        "live systems, credential stores, or networks were accessed in "
        "producing this report."
    )
    lines.append("")

    lines.append("## 1. Strength Analysis")
    lines.append("")
    lines.append(f"- **Score:** {analysis.get('score', 0)} / 100")
    lines.append(f"- **Rating:** {analysis.get('rating', 'N/A')}")
    lines.append(f"- **Entropy:** {analysis.get('entropy_bits', 0)} bits")
    lines.append(
        f"- **Known Common Password:** "
        f"{'Yes ⚠️' if analysis.get('is_common_weak') else 'No'}"
    )
    lines.append("")
    lines.append("### Complexity Checklist")
    lines.append(_complexity_line("At least 12 characters", complexity.get("length_ok_12", False)))
    lines.append(_complexity_line("At least 8 characters", complexity.get("length_ok_8", False)))
    lines.append(_complexity_line("Contains lowercase letters", complexity.get("has_lowercase", False)))
    lines.append(_complexity_line("Contains uppercase letters", complexity.get("has_uppercase", False)))
    lines.append(_complexity_line("Contains digits", complexity.get("has_digit", False)))
    lines.append(_complexity_line("Contains symbols", complexity.get("has_symbol", False)))
    lines.append(_complexity_line("No repeated character runs", complexity.get("no_repeated_chars", False)))
    lines.append("")

    lines.append("## 2. Estimated Offline Crack Time")
    lines.append("")
    lines.append(
        f"- **Assumed attacker hash rate:** "
        f"{crack_time.get('assumed_hash_rate', 0):,} hashes/second "
        f"(illustrative offline GPU benchmark)"
    )
    lines.append(f"- **Estimated average time to crack:** {crack_time.get('human_readable', 'N/A')}")
    lines.append(
        "- *Note: this assumes a fast, unsalted hash. Properly salted, "
        "slow hashes (bcrypt/Argon2) would increase this time by several "
        "orders of magnitude.*"
    )
    lines.append("")

    if wordlist:
        lines.append("## 3. Generated Auditing Wordlist")
        lines.append("")
        label = wordlist_base_keyword or "base keyword"
        lines.append(
            f"Generated from base keyword **`{label}`** for OFFLINE audit "
            f"use (e.g. checking existing credential hashes for reuse of "
            f"predictable, organization-related passwords). "
            f"{len(wordlist)} candidates generated."
        )
        lines.append("")
        preview = wordlist[:50]
        lines.append("```")
        lines.extend(preview)
        if len(wordlist) > len(preview):
            lines.append(f"... (+{len(wordlist) - len(preview)} more)")
        lines.append("```")
        lines.append("")

    section_num = 4 if wordlist else 3
    lines.append(f"## {section_num}. Defensive Policy Recommendations")
    lines.append("")
    for rec in generate_policy_recommendations(analysis):
        lines.append(f"- {rec}")
    lines.append("")

    lines.append("---")
    lines.append(
        "*Report generated by the open-source Password Security Auditing "
        "Toolkit — an educational, defensive-use-only project. This tool "
        "performs no live credential extraction and no active network "
        "brute-forcing.*"
    )

    return "\n".join(lines)
